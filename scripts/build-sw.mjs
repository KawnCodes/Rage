// Generates public/sw.js: the offline cache. It lists every game file and a
// version hash of their contents, so any change to the game makes phones
// download the new version the next time they're online.
//   node scripts/build-sw.mjs          (run automatically by `npm start`)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'public');
const OUT = path.join(root, 'sw.js');

export function gameFiles() {
  const out = [];
  const walk = (dir, rel) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (ent.name.startsWith('.')) continue;
      const abs = path.join(dir, ent.name);
      const r = rel ? `${rel}/${ent.name}` : ent.name;
      if (ent.isDirectory()) walk(abs, r);
      else if (r !== 'sw.js') out.push(r);
    }
  };
  walk(root, '');
  return out;
}

export function version(files = gameFiles()) {
  const h = crypto.createHash('sha256');
  for (const f of files) { h.update(f); h.update('\0'); h.update(fs.readFileSync(path.join(root, f))); }
  return h.digest('hex').slice(0, 16);
}

export function render(files = gameFiles()) {
  const v = version(files);
  return `// GENERATED by scripts/build-sw.mjs — do not edit by hand.
// Offline cache for RAGE: every file below is stored on the device after the
// first visit, so the game works with no internet. When the game changes, this
// file changes (new VERSION), the browser notices next time it's online,
// downloads the new files, and the page offers "Update ready".
const VERSION = '${v}';
const CACHE = 'rage-' + VERSION;
const FILES = ${JSON.stringify(['./', ...files.map((f) => `./${f}`)], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('rage-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  // Only our own game files. Never the lobby API, never other sites.
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  const scope = new URL(self.registration.scope);
  if (!url.pathname.startsWith(scope.pathname)) return;
  if (url.pathname.startsWith(scope.pathname + 'api/')) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true }) ||
      (req.mode === 'navigate' ? await cache.match('./') : undefined);
    if (hit) return hit;
    return fetch(req);
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'version' && event.source) event.source.postMessage({ version: VERSION });
});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (old !== text) fs.writeFileSync(OUT, text);
  console.log(`sw.js: version ${version()} (${gameFiles().length} files)${old === text ? ', unchanged' : ''}`);
}
